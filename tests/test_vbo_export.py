def test_vbo_obd_columns_import():
    log = DataLog()
    log.from_vbo_log(_DRAGY_OBD_VBO.splitlines())
    for name in (
        "Engine RPM",
        "Accelerator Pos",
        "Brake Press",
        "Engine Oil Temp",
        "Coolant Temp",
        "Manifold Press",
    ):
        assert name in log.channels, f"missing channel {name}"
    rpms = [m.value for m in log.channels["Engine RPM"].messages]
    assert rpms == [4116.0, 736.0]


