def _synthetic_gps_log():
    log = DataLog()
    n = 100
    log.add_channel("Ground Speed", "km/h", float, 2)
    log.channels["Ground Speed"].messages = [
        Message(i * 0.04, 100.0 + i * 0.1) for i in range(n)
    ]
    log.add_channel("GPS Latitude", "deg", float, 7)
    log.channels["GPS Latitude"].messages = [
        Message(i * 0.04, 39.54 + i * 1e-6) for i in range(n)
    ]
    log.add_channel("GPS Longitude", "deg", float, 7)
    log.channels["GPS Longitude"].messages = [
        Message(i * 0.04, -122.33 + i * 1e-6) for i in range(n)
    ]
    log.add_channel("GPS Altitude", "m", float, 2)
    log.channels["GPS Altitude"].messages = [
        Message(i * 0.04, 85.0) for i in range(n)
    ]
    log.add_channel("Engine RPM", "rpm", float, 0)
    log.channels["Engine RPM"].messages = [
        Message(i * 0.04, 3000.0 + i) for i in range(n)
    ]
    return log


def test_vbo_export_roundtrip():
    log = _synthetic_gps_log()
    log.resample(25)
    with tempfile.NamedTemporaryFile(suffix=".vbo", delete=False) as tmp:
        tmp_path = tmp.name
    try:
        assert write_vbo(log, tmp_path)
        with open(tmp_path, encoding="utf-8") as f:
            text = f.read()
        assert "[column names]" in text
        assert "[data]" in text
        assert "sats time lat long velocity heading height" in text
        assert "rpm-obd" in text

        reparsed = DataLog()
        reparsed.from_vbo_log(text.splitlines())
        assert "Ground Speed" in reparsed.channels
        assert "GPS Latitude" in reparsed.channels
        assert "Engine RPM" in reparsed.channels
        speeds = [m.value for m in reparsed.channels["Ground Speed"].messages]
        assert abs(speeds[0] - 100.0) < 0.01
        assert abs(speeds[-1] - 109.9) < 0.11
        assert abs(speeds[50] - 105.0) < 0.01
        lats = [m.value for m in reparsed.channels["GPS Latitude"].messages]
        assert abs(lats[0] - 39.54) < 1e-6
    finally:
        os.remove(tmp_path)


def test_vbo_export_dynamic_extras_and_unit_guard():
    log = _synthetic_gps_log()
    log.add_channel("Gear", "", float, 0)
    log.channels["Gear"].messages = [Message(i * 0.04, 3.0) for i in range(100)]
    log.add_channel("Chassis Yaw Rate", "deg/s", float, 3)
    log.channels["Chassis Yaw Rate"].messages = [Message(i * 0.04, 1.5) for i in range(100)]
    log.add_channel("Brake Press", "bar", float, 2)
    log.channels["Brake Press"].messages = [Message(i * 0.04, 5.0) for i in range(100)]
    log.resample(25)
    with tempfile.NamedTemporaryFile(suffix=".vbo", delete=False) as tmp:
        tmp_path = tmp.name
    try:
        assert write_vbo(log, tmp_path)
        with open(tmp_path, encoding="utf-8") as f:
            text = f.read()
        assert "gear-canbus" in text
        assert "yaw_rate-canbus" in text
        # Unit mismatch (bar vs kPa column) must be skipped, not mislabeled.
        assert "brake_pressure-obd" not in text
    finally:
        os.remove(tmp_path)


def test_vbo_export_pedal_preference():
    log = _synthetic_gps_log()
    for name in ("Accelerator Pos", "Throttle Pos"):
        log.add_channel(name, "%", float, 2)
        log.channels[name].messages = [Message(i * 0.04, 20.0) for i in range(100)]
    log.resample(25)
    with tempfile.NamedTemporaryFile(suffix=".vbo", delete=False) as tmp:
        tmp_path = tmp.name
    try:
        assert write_vbo(log, tmp_path)
        with open(tmp_path, encoding="utf-8") as f:
            text = f.read()
        assert "acceleration-obd" in text
        assert "throttle_pos-canbus" not in text
    finally:
        os.remove(tmp_path)
    throttle_only = _synthetic_gps_log()
    throttle_only.add_channel("Throttle Pos", "%", float, 2)
    throttle_only.channels["Throttle Pos"].messages = [
        Message(i * 0.04, 20.0) for i in range(100)
    ]
    throttle_only.resample(25)
    with tempfile.NamedTemporaryFile(suffix=".vbo", delete=False) as tmp:
        tmp_path = tmp.name
    try:
        assert write_vbo(throttle_only, tmp_path)
        with open(tmp_path, encoding="utf-8") as f:
            text = f.read()
        assert "throttle_pos-canbus" in text
    finally:
        os.remove(tmp_path)
    log = DataLog()
    log.add_channel("Engine RPM", "rpm", float, 0)
    log.channels["Engine RPM"].messages = [Message(0.0, 3000.0)]
    with tempfile.NamedTemporaryFile(suffix=".vbo", delete=False) as tmp:
        tmp_path = tmp.name
    try:
        assert not write_vbo(log, tmp_path)
    finally:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)


