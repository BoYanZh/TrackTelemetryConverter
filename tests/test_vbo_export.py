def test_vbo_export_from_dlap_source():
    with tempfile.TemporaryDirectory() as tmp_dir:
        dlap_path = os.path.join(tmp_dir, "session.dlap")
        _write_minimal_dlap(dlap_path)
        log = DataLog()
        log.from_dlap_log(dlap_path)
        log.resample(25)
        vbo_path = os.path.join(tmp_dir, "session.vbo")
        assert write_vbo(log, vbo_path)
        with open(vbo_path, encoding="utf-8") as f:
            lines = f.readlines()
        data_idx = next(
            i for i, line in enumerate(lines) if line.strip() == "[data]"
        )
        assert len(lines) - data_idx - 1 == len(
            log.channels["GPS Latitude"].messages
        )


def test_cli_vbo_flag_and_source_guard():
    with tempfile.TemporaryDirectory() as tmp_dir:
        src = os.path.join(tmp_dir, "in.vbo")
        with open(src, "w", encoding="utf-8") as f:
            f.write(_DRAGY_OBD_VBO)
        # --output stem matches the source stem, so the plain .vbo target
        # would replace the input: the exporter must use the _export guard.
        result = _run_cli_in_process(
            [src, "VBO", "--output", os.path.join(tmp_dir, "in"), "--vbo"]
        )
        assert result.returncode == 0, result.stdout + result.stderr
        assert os.path.isfile(os.path.join(tmp_dir, "in_export.vbo"))
        assert "Saved .vbo track file" in result.stdout
        with open(src, encoding="utf-8") as f:
            assert "Generated by dragy Lap" in f.read()
