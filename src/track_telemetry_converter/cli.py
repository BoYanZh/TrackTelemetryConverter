def _load_anchor_file(anchor_path):
    """Load custom ACTI track profiles merged over the built-in table."""
    if not anchor_path:
        return None
    if not os.path.isfile(anchor_path):
        print(f"ERROR: Anchor file {anchor_path} does not exist")
        sys.exit(1)
    try:
        with open(anchor_path, encoding="utf-8") as handle:
            profiles = json.load(handle)
    except (OSError, ValueError) as exc:
        print(f"ERROR: Invalid anchor file {anchor_path}: {exc}")
        sys.exit(1)
    if not isinstance(profiles, dict):
        print(f"ERROR: Anchor file {anchor_path} must contain a JSON object")
        sys.exit(1)
    return profiles


def _extract_acti_log(args, data_log, target_lap):
    """Extract ACTI sim channels, placing Car Coord through the track profile."""
    from .parsers.acti_parser import (
        ACTI_TRACK_PROFILES,
        THUNDERHILL_AUTO_KEY,
    )

    anchors = _load_anchor_file(args.anchor)
    profiles = dict(ACTI_TRACK_PROFILES)
    if anchors:
        for key, cfg in anchors.items():
            merged = dict(profiles.get(key, {}))
            merged.update(cfg)
            profiles[key] = merged
    valid_tracks = [*sorted(profiles), THUNDERHILL_AUTO_KEY]
    if not args.track or args.track not in [*profiles, THUNDERHILL_AUTO_KEY]:
        print(
            "ERROR: ACTI input needs --track with one of: "
            + ", ".join(valid_tracks),
        )
        sys.exit(1)
    if args.track == THUNDERHILL_AUTO_KEY:
        print("Extracting ACTI sim telemetry (track profile: thunderhill_auto; "
              "per-file Car Coord X probe selects thunderhill_west/east_bypass)...")
    else:
        print(f"Extracting ACTI sim telemetry (track profile: {args.track})...")
    try:
        data_log.from_acti_log(args.log, target_lap=target_lap,
                               track=args.track, anchors=profiles)
    except ValueError as exc:
        print(f"ERROR: {exc}")
        sys.exit(1)


def _extract_log_data(args, active_type, data_log, stint_arg, target_session):
    """Populate channels from the input file according to its type."""
    print("Loading log...")

    if active_type == "CAN":
        _extract_can_log(args, data_log)
        return
    if active_type == "RCZ":
        _extract_rcz_log(args, data_log, active_type, stint_arg, target_session)
        return
    if active_type == "ACTI":
        _extract_acti_log(args, data_log, args.lap)
        return
    if active_type in _TEXT_LOG_READERS:
        message, method, use_lap = _TEXT_LOG_READERS[active_type]
        lines = _read_input_lines(args.log)
        print(message)
        if use_lap:
            getattr(data_log, method)(lines, target_lap=args.lap)
        else:
            getattr(data_log, method)(lines)
        return
    if active_type in _PATH_LOG_READERS:
        message, method, use_lap = _PATH_LOG_READERS[active_type]
        print(message)
        if use_lap:
            getattr(data_log, method)(args.log, target_lap=args.lap)
        else:
            getattr(data_log, method)(args.log)
        return


def _detect_gps_venue(data_log):
    """Return a GPS-detected venue name, or "" when GPS is unusable/unknown."""
    from .channels import CH_GPS_LATITUDE, CH_GPS_LONGITUDE
    from .metadata import detect_venue_from_gps

    channels = getattr(data_log, "channels", {})
    lat_ch = channels.get(CH_GPS_LATITUDE)
    lon_ch = channels.get(CH_GPS_LONGITUDE)
    if lat_ch is None or lon_ch is None:
        return ""
    lats = [m.value for m in lat_ch.messages]
    lons = [m.value for m in lon_ch.messages]
    return detect_venue_from_gps(lats, lons)


def _resolve_venue_name(args, data_log):
    """Resolve the venue through strings, then GPS area detection.

    Precedence: explicit --venue_name > file metadata / RCZ track > filename.
    An explicit --venue_name is never overridden. When the string result
    names no known track, GPS area detection fills in (e.g. AiM free text
    like "new track 01"); anything still unknown passes through unchanged.
    """
    from .metadata import is_meaningful_venue, venue_facility

    meta = getattr(data_log, "metadata", {})

    venue_name = args.venue_name if args.venue_name else meta.get("venue_name", "")
    if not venue_name and hasattr(data_log, "rcz_metadata") and data_log.rcz_metadata.get("trackName"):
        venue_name = data_log.rcz_metadata.get("trackName")

    if not venue_name:
        filename = os.path.basename(args.log)
        venue_name = _normalize_venue(filename)
        if venue_name == filename:
            venue_name = _normalize_venue(meta.get("event_session", meta.get("Session", "")))
    else:
        venue_name = _normalize_venue(venue_name)

    if not args.venue_name:
        gps_venue = _detect_gps_venue(data_log)
        if gps_venue and (not is_meaningful_venue(venue_name)
                          or venue_facility(venue_name) != venue_facility(gps_venue)):
            print(f"GPS-detected venue: {gps_venue} (strings gave {venue_name!r})")
            venue_name = gps_venue
    return venue_name


def _build_motec_log(args, data_log, direction=None):
    """Resolve venue/event/driver metadata and build the MoTeC log.

    ``direction`` ("cw"/"ccw"/None) appends " CW"/" CCW" to the venue only
    (never to event/session metadata, which derive from the plain venue).
    An explicit --venue_name always wins and is never suffixed.
    """
    meta = getattr(data_log, "metadata", {})

    venue_name = _resolve_venue_name(args, data_log)

    event_name = args.event_name if args.event_name else meta.get("event_name", "")
    if not event_name and venue_name:
        event_name = venue_name.replace("_", " ").title() + " Track Day" if not venue_name.endswith("Track Day") else venue_name

    if direction in ("cw", "ccw") and not getattr(args, "venue_name", ""):
        suffix = " CW" if direction == "cw" else " CCW"
        if venue_name and not venue_name.upper().endswith((" CW", " CCW")):
            venue_name = f"{venue_name}{suffix}"

    data_log.metadata["venue_name"] = venue_name

    driver_name = args.driver if args.driver else meta.get("driver", meta.get("Racer", ""))
    if not driver_name:
        driver_name = "Unknown Driver"

    vehicle_name = args.vehicle_id if args.vehicle_id else meta.get(
        "vehicle_id", meta.get("Vehicle", ""),
    )

    motec_log = MotecLog()
    if data_log.datetime is not None:
        motec_log.datetime = data_log.datetime
    motec_log.driver = driver_name
    motec_log.vehicle_id = vehicle_name
    motec_log.vehicle_weight = args.vehicle_weight
    motec_log.vehicle_type = args.vehicle_type
    motec_log.vehicle_comment = args.vehicle_comment
    motec_log.venue_name = venue_name
    motec_log.event_name = event_name
    motec_log.event_session = args.event_session if args.event_session else meta.get("event_session", "")
    motec_log.long_comment = args.long_comment if args.long_comment else meta.get("long_comment", meta.get("Comment", ""))
    motec_log.short_comment = args.short_comment if args.short_comment else meta.get("short_comment", "")

    motec_log.initialize()
    motec_log.add_all_channels(data_log)
    return motec_log


def _write_all_outputs(args, motec_log, data_log, ld_filename, ldx_filename, output_targets):
    """Write the .ld/.ldx pair plus every requested auxiliary export."""
    print("Saving MoTeC log...")
    output_dir = os.path.dirname(ld_filename)
    if output_dir and not os.path.isdir(output_dir):
        print(f"Directory '{output_dir}' does not exist, will create it")
        os.makedirs(output_dir, exist_ok=True)

    ensure_output_targets(
        output_targets,
        force=getattr(args, "force", False),
        source_path=args.log,
    )
    try:
        atomic_write_motec_pair(motec_log, data_log, ld_filename, ldx_filename)
        print(f"Saved .ld file: {ld_filename}")
        print(f"Saved .ldx file: {ldx_filename}")
    except PermissionError as exc:
        raise PermissionError(
            f"output is locked; close the file in MoTeC i2 and retry: {ld_filename}",
        ) from exc

    if args.gpx:
        gpx_filename = os.path.splitext(ld_filename)[0] + ".gpx"
        if motec_log.write_gpx(gpx_filename, data_log):
            print(f"Saved .gpx track file: {gpx_filename}")

    if args.kml:
        kml_filename = os.path.splitext(ld_filename)[0] + ".kml"
        if motec_log.write_kml(kml_filename, data_log):
            print(f"Saved .kml Google Earth file: {kml_filename}")

    if args.csv:
        csv_filename = _csv_output_path(ld_filename, args.log)
        if motec_log.write_csv(csv_filename, data_log, wallclock=getattr(args, "csv_wallclock", False)):
            print(f"Saved .csv data file: {csv_filename}")

    if getattr(args, "vbo", False):
        vbo_filename = _vbo_output_path(ld_filename, args.log)
        columns = getattr(args, "vbo_columns_parsed", None)
        if motec_log.write_vbo(vbo_filename, data_log, columns):
            print(f"Saved .vbo track file: {vbo_filename}")

    if getattr(args, "dlap", False):
        dlap_filename = _dlap_output_path(ld_filename, args.log)
        if motec_log.write_dlap(dlap_filename, data_log):
            print(f"Saved .dlap track file: {dlap_filename}")

    print("Done!")
    return output_targets


def process_one_file(args, stint_override=None, output_override=None,
                     session_override=None):
    stint_arg, out_base, target_session = _resolve_process_args(
        args, stint_override, output_override, session_override,
    )
    active_type = _detect_process_type(args)

    stint_files = _fanout_rcz_stints(args, active_type, stint_arg, target_session, out_base)
    if stint_files is not None:
        return stint_files

    ld_filename, ldx_filename, output_targets = _output_paths(args, out_base)
    # With --direction-suffix and default naming the final names gain _cw/_ccw
    # only after parsing (e.g. ACTI input foo.ld -> foo_cw.ld, which no longer
    # collides with the input). Defer the guard to the suffixed names then;
    # _write_all_outputs still enforces it before any write.
    if not (getattr(args, "direction_suffix", False) and out_base is None):
        ensure_output_targets(
            output_targets,
            force=getattr(args, "force", False),
            source_path=args.log,
        )

    data_log = DataLog()
    _extract_log_data(args, active_type, data_log, stint_arg, target_session)

    if not data_log.channels:
        print("ERROR: Failed to find any channels in log data")
        sys.exit(1)

    print(f"Parsed {data_log.duration():.1f}s log with {len(data_log.channels)} channels:")
    for channel in data_log.channels.values():
        print(f"\t{channel}")

    resample_freq = data_log.resample(args.frequency, mask_interp_gaps=args.mask_interp_gaps)
    print(f"Resampled channels at {resample_freq:.1f} Hz...")

    print("Calculating math channels (g-source: {})...".format(getattr(args, "g_source", "auto")))
    data_log.calculate_math_channels(
        g_source=getattr(args, "g_source", "auto"),
        gear_ratio_thresholds=getattr(args, "gear_ratio_thresholds", None),
        gearbox=getattr(args, "gearbox", None),
    )

    print("Converting to MoTeC log...")

    direction, total = None, 0.0
    if getattr(args, "direction_suffix", False):
        direction, total = _detect_track_direction(data_log)
        if direction is None:
            print("WARNING: --direction-suffix skipped: no usable GPS Heading "
                  "(no GPS data or indeterminate direction)")
        elif getattr(args, "venue_name", ""):
            print("WARNING: --direction-suffix venue ignored: --venue_name is explicit; "
                  "keeping user value")

    motec_log = _build_motec_log(args, data_log, direction=direction)

    if getattr(args, "direction_suffix", False):
        ld_filename, ldx_filename, output_targets = _maybe_apply_direction_suffix(
            args, data_log, ld_filename, ldx_filename, output_targets,
            output_override=output_override,
            direction=direction, total=total,
        )

    return _write_all_outputs(args, motec_log, data_log, ld_filename, ldx_filename, output_targets)


