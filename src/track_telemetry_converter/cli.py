def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)

    if str(args.frequency).lower() != "auto":
        try:
            if float(args.frequency) <= 0:
                print("ERROR: --frequency must be positive or 'auto'")
                sys.exit(1)
        except ValueError:
            print(f"ERROR: Invalid --frequency value '{args.frequency}'. Must be a number or 'auto'")
            sys.exit(1)

    if not math.isfinite(args.min_lap_sec) or args.min_lap_sec <= 0:
        print("ERROR: --min-lap-sec must be a positive finite number")
        sys.exit(1)

    args.vbo_columns_parsed = None
    if getattr(args, "vbo_columns", None):
        from .exporters.vbo_export import parse_vbo_columns

        try:
            args.vbo_columns_parsed = parse_vbo_columns(args.vbo_columns)
        except ValueError as exc:
            print(f"ERROR: {exc}")
            sys.exit(1)

    if args.log:
        args.log = os.path.expanduser(args.log)
    if args.dbc:
        args.dbc = os.path.expanduser(args.dbc)
    if args.output:
        args.output = os.path.expanduser(args.output)
    if args.output_dir:
        args.output_dir = os.path.expanduser(args.output_dir)
    if args.log.lower().endswith(".rcz") and args.log_type != "RCZ":
        print(f"WARNING: Overriding --log_type '{args.log_type}' to 'RCZ' because input file has .rcz extension")
        args.log_type = "RCZ"

    if args.log.lower().endswith((".xrk", ".xrz")) and args.log_type != "XRK":
        print(f"WARNING: Overriding --log_type '{args.log_type}' to 'XRK' because input file has .xrk/.xrz extension")
        args.log_type = "XRK"

    if args.log.lower().endswith(".fit") and args.log_type != "FIT":
        print(f"WARNING: Overriding --log_type '{args.log_type}' to 'FIT' because input file has .fit extension")
        args.log_type = "FIT"

    if os.path.isdir(args.log):
        return _batch_convert(args)

    return _convert_single_input(args)


def _export_rcz_backup(args, backup_sessions):
    """Export every session/stint of a RaceChrono backup archive. Returns exit code."""
    if args.output:
        print("ERROR: --output cannot be used with --session all; use --output-dir")
        return 1
    if str(args.stint).lower() != "all":
        print("ERROR: --session all requires --stint all")
        return 1

    output_dir = args.output_dir
    if not output_dir:
        output_dir = os.path.splitext(args.log)[0] + "_sessions"
    jobs = []
    all_targets = []
    for session in backup_sessions:
        for stint in session.stints:
            stem = session.session_id
            if len(session.stints) > 1:
                stem += f"_stint{stint}"
            output_base = os.path.join(output_dir, stem)
            _, _, targets = _output_paths(args, output_base)
            jobs.append((session.session_id, stint, output_base))
            all_targets.extend(targets)
    try:
        ensure_output_targets(
            all_targets,
            force=args.force,
            source_path=args.log,
        )
    except (OSError, ValueError) as exc:
        print(f"ERROR: {exc}")
        print("Preflight failed; no sessions were exported.")
        return 1

    succeeded = 0
    failures = []
    for session_id, stint, output_base in jobs:
        print(f"\n=== Exporting {session_id} stint {stint} ===")
        try:
            _process_one(
                args,
                stint_override=str(stint),
                output_override=output_base,
                session_override=session_id,
            )
            succeeded += 1
        except SystemExit as exc:
            failures.append((session_id, stint, f"exit code {exc.code}"))
        except Exception as exc:
            failures.append((session_id, stint, str(exc)))
        if failures and failures[-1][0:2] == (session_id, stint):
            print("ERROR: {} stint {} failed: {}".format(*failures[-1]))

    print(
        f"\nRCZ backup export complete: {succeeded} succeeded, {len(failures)} failed.",
    )
    return 1 if failures else 0


def _unsupported_batch_skips(candidates, wanted):
    """List (path, reason) skips for non-whitelisted AUTO candidates.

    Video, configs, images, ... are skipped, never failed. Our own outputs
    (.ld/.ldx), the .dbc sidecar, and dotfiles stay silently ignored so
    re-runs keep their skip counts.
    """
    from .parsers import DBC_EXTENSION, OUTPUT_EXTENSIONS

    skips = []
    for path in sorted(candidates):
        if path.lower().endswith(wanted):
            continue
        if not os.path.isfile(path):
            continue
        ext = os.path.splitext(path)[1].lower()
        if ext in OUTPUT_EXTENSIONS or ext == DBC_EXTENSION:
            continue
        if os.path.basename(path).startswith("."):
            continue
        skips.append((path, "unsupported extension (not a convertible log)"))
    return skips


def _batch_single_file_task(task):
    """Run one batch file conversion; top-level so it is picklable.

    ``task`` is ``(index, fpath, file_args, detected)`` where ``file_args``
    is a per-file copy of the parsed CLI namespace. Captures stdout in the
    worker process and returns ``(index, fpath, detected, code, text)``.
    """
    import io
    from contextlib import redirect_stdout

    index, fpath, file_args, detected = task
    buffer = io.StringIO()
    try:
        with redirect_stdout(buffer):
            code = _convert_single_input(file_args)
    except SystemExit as exc:
        code = exc.code if isinstance(exc.code, int) else 1
        buffer.write(f"ERROR: exited with code {code}\n")
    except Exception as exc:
        code = 1
        buffer.write(f"ERROR: {type(exc).__name__}: {exc}\n")
    return (index, fpath, detected, code, buffer.getvalue())


def _batch_output_override(fpath, detected, output_dir):
    """Resolve the per-file batch output base (without extension).

    With ``--output-dir`` every output (``.ld``/``.ldx``, ACTI ``_gps``
    stems, ``--direction-suffix`` ``_cw``/``_ccw`` names, auxiliary
    exports) is redirected into that directory, flattened to the plain
    input filename (subdirectory structure is not preserved). Name
    collisions between flattened files follow the existing
    ``ensure_output_targets``/``--force`` semantics. Without
    ``--output-dir`` behaviour is unchanged: ``None`` (next to input),
    except ACTI which gains a ``_gps`` suffix next to the input.
    """
    if output_dir:
        stem = os.path.splitext(os.path.basename(fpath))[0]
        if detected == "ACTI":
            stem += "_gps"
        return os.path.join(output_dir, stem)
    if detected == "ACTI":
        # ACTI input is already a .ld file: suffix outputs instead of
        # refusing to replace the input on every file.
        return os.path.splitext(fpath)[0] + "_gps"
    return None


def _batch_convert(args):
    """Convert every recognized log in a directory, detecting each file's format.

    With AUTO (recommended), each file's type is detected individually, so RCZ,
    CSV, VBO, DLAP, IBT, XRK, and FIT inputs can be mixed in one run. Only
    whitelisted convertible extensions are attempted (see
    parsers.SUPPORTED_INPUT_EXTENSIONS); anything else (video, configs,
    images, ...) is counted as skipped, never failed. Outputs are
    written next to each input unless --output-dir is given, in which case
    they are flattened to plain filenames inside that directory (created
    when missing); existing outputs are skipped unless --force is
    given. Returns exit code (0 unless at least one file failed).
    """
    import copy
    import io
    from contextlib import redirect_stdout

    dir_path = args.log
    if args.output:
        print("ERROR: --output cannot be used with a directory; outputs are written next to each input")
        return 1
    if args.list_sessions:
        print("ERROR: --list-sessions cannot be used with a directory; run it on a single RCZ backup")
        return 1
    if args.session is not None and str(args.session).lower() != "all":
        print("ERROR: --session ID cannot be used with a directory; use --session all to expand backup archives")
        return 1
    if str(getattr(args, "stint", "all")).lower() != "all":
        print("ERROR: --stint cannot be used with a directory")
        return 1
    if str(getattr(args, "lap", "all")).lower() != "all":
        print("ERROR: --lap cannot be used with a directory")
        return 1

    if args.log_type == "AUTO":
        wanted = _BATCH_AUTO_EXTENSIONS
    else:
        wanted = _BATCH_TYPE_EXTENSIONS.get(args.log_type, ())
    if getattr(args, "recursive", False):
        candidates = [
            os.path.join(root, name)
            for root, _, names in os.walk(dir_path)
            for name in names
        ]
    else:
        candidates = [
            os.path.join(dir_path, name)
            for name in os.listdir(dir_path)
            if os.path.isfile(os.path.join(dir_path, name))
        ]
    files = sorted(path for path in candidates if path.lower().endswith(wanted))
    if not files:
        print("ERROR: No convertible logs ({}) found in directory '{}'".format(", ".join(wanted), dir_path))
        return 1

    expand_backups = args.session is not None and str(args.session).lower() == "all"
    output_dir = getattr(args, "output_dir", None)
    if output_dir and not os.path.isdir(output_dir):
        print(f"Directory '{output_dir}' does not exist, will create it")
        os.makedirs(output_dir, exist_ok=True)
    converted, skipped, failed = [], [], []
    if args.log_type == "AUTO":
        skipped.extend(_unsupported_batch_skips(candidates, wanted))
    try:
        jobs = int(getattr(args, "jobs", 1))
    except (TypeError, ValueError):
        jobs = 1
    if jobs <= 1:
        for index, fpath in enumerate(files, 1):
            file_args = copy.copy(args)
            file_args.log = fpath
            file_args.output = None
            file_args._batch_mode = True
            detected = args.log_type
            if args.log_type == "AUTO":
                if fpath.lower().endswith(_BATCH_TYPE_EXTENSIONS["CAN"]):
                    if not args.dbc or not os.path.isfile(args.dbc or ""):
                        skipped.append((fpath, "CAN log requires --dbc"))
                        continue
                    detected = "CAN"
                else:
                    detected = auto_detect_log_type(fpath)
                file_args.log_type = detected
            print("=" * 80)
            print(f"Processing [{index}/{len(files)}]: {fpath} (type: {detected})")
            file_args.output = _batch_output_override(fpath, detected, output_dir)

            if fpath.lower().endswith(".rcz") and detected == "RCZ":
                try:
                    backup_sessions = discover_rcz_sessions(fpath)
                except Exception as exc:
                    print(f"ERROR: Failed to inspect RCZ archive: {exc}")
                    failed.append(fpath)
                    continue
                if backup_sessions:
                    if not expand_backups:
                        print(
                            f"Skipped: RaceChrono backup contains {len(backup_sessions)} sessions; "
                            "re-run with --session all to expand it, or convert one "
                            "session with '--session ID' on the single file.",
                        )
                        skipped.append((fpath, "backup archive (use --session all)"))
                        continue
                else:
                    # A single-session RCZ must not inherit --session all.
                    file_args.session = None

            buffer = io.StringIO()
            try:
                with redirect_stdout(buffer):
                    code = _convert_single_input(file_args)
            except SystemExit as exc:
                code = exc.code if isinstance(exc.code, int) else 1
                buffer.write(f"ERROR: exited with code {code}\n")
            except Exception as exc:
                code = 1
                buffer.write(f"ERROR: {type(exc).__name__}: {exc}\n")
            text = buffer.getvalue()
            sys.stdout.write(text)
            if not text.endswith("\n"):
                print()
            if code == 0:
                converted.append(fpath)
            elif "already exists" in text:
                skipped.append((fpath, "output already exists (use --force)"))
            else:
                failed.append(fpath)
    else:
        import concurrent.futures

        tasks = []
        for index, fpath in enumerate(files, 1):
            file_args = copy.copy(args)
            file_args.log = fpath
            file_args.output = None
            file_args._batch_mode = True
            detected = args.log_type
            if args.log_type == "AUTO":
                if fpath.lower().endswith(_BATCH_TYPE_EXTENSIONS["CAN"]):
                    if not args.dbc or not os.path.isfile(args.dbc or ""):
                        skipped.append((fpath, "CAN log requires --dbc"))
                        continue
                    detected = "CAN"
                else:
                    detected = auto_detect_log_type(fpath)
                file_args.log_type = detected
            file_args.output = _batch_output_override(fpath, detected, output_dir)

            if fpath.lower().endswith(".rcz") and detected == "RCZ":
                try:
                    backup_sessions = discover_rcz_sessions(fpath)
                except Exception as exc:
                    print("=" * 80)
                    print(f"Processing [{index}/{len(files)}]: {fpath} (type: {detected})")
                    print(f"ERROR: Failed to inspect RCZ archive: {exc}")
                    failed.append(fpath)
                    continue
                if backup_sessions:
                    if not expand_backups:
                        print("=" * 80)
                        print(f"Processing [{index}/{len(files)}]: {fpath} (type: {detected})")
                        print(
                            f"Skipped: RaceChrono backup contains {len(backup_sessions)} sessions; "
                            "re-run with --session all to expand it, or convert one "
                            "session with '--session ID' on the single file.",
                        )
                        skipped.append((fpath, "backup archive (use --session all)"))
                        continue
                else:
                    # A single-session RCZ must not inherit --session all.
                    file_args.session = None
            tasks.append((index, fpath, file_args, detected))

        print(f"Batch parallel mode: {len(tasks)} files with {jobs} workers")
        with concurrent.futures.ProcessPoolExecutor(max_workers=jobs) as pool:
            future_map = {
                pool.submit(_batch_single_file_task, task): task[0]
                for task in tasks
            }
            for future in concurrent.futures.as_completed(future_map):
                try:
                    index, fpath, detected, code, text = future.result()
                except Exception as exc:
                    task_index = future_map[future]
                    fpath = files[task_index - 1]
                    detected = args.log_type
                    code, text = 1, f"ERROR: {type(exc).__name__}: {exc}\n"
                    index = task_index
                print("=" * 80)
                print(f"Processing [{index}/{len(files)}]: {fpath} (type: {detected})")
                sys.stdout.write(text)
                if not text.endswith("\n"):
                    print()
                sys.stdout.flush()
                if code == 0:
                    converted.append(fpath)
                elif "already exists" in text:
                    skipped.append((fpath, "output already exists (use --force)"))
                else:
                    failed.append(fpath)

    print("=" * 80)
    print(
        f"Batch complete: {len(converted)} converted, {len(skipped)} skipped, {len(failed)} failed.",
    )
    for fpath, reason in skipped:
        print(f"  skipped: {fpath} ({reason})")
    for fpath in failed:
        print(f"  failed: {fpath}")
    return 1 if failed else 0


def _convert_single_input(args):
    if not os.path.isfile(args.log):
        print(f"ERROR: log file {args.log} does not exist")
        return 1

    if args.log_type == "RCZ":
        try:
            backup_sessions = discover_rcz_sessions(args.log)
        except (OSError, ValueError, zipfile.BadZipFile) as exc:
            print(f"ERROR: Failed to inspect RCZ archive: {exc}")
            return 1
        if args.list_sessions:
            if not backup_sessions:
                print("This RCZ contains one root session; --list-sessions is for backup archives.")
                return 0
            print(f"Found {len(backup_sessions)} sessions:")
            print("Session ID\tTrack\tDuration\tLaps\tStints")
            for session in backup_sessions:
                print(
                    "{}\t{}\t{:.1f}s\t{}\t{}".format(
                        session.session_id,
                        session.track_name,
                        session.duration_sec,
                        session.lap_count,
                        ",".join(str(value) for value in session.stints),
                    ),
                )
            return 0
        if backup_sessions:
            if not args.session:
                print(
                    f"ERROR: RaceChrono backup contains {len(backup_sessions)} sessions; use "
                    "--list-sessions, --session ID, or --session all.",
                )
                return 1
            if str(args.session).lower() != "all":
                selected = next(
                    (
                        item for item in backup_sessions
                        if item.session_id == args.session
                    ),
                    None,
                )
                if selected is None:
                    print(f"ERROR: Unknown RCZ session ID '{args.session}'.")
                    print("Use --list-sessions to see valid IDs.")
                    return 1
                if args.output_dir:
                    print("ERROR: --output-dir is only valid with --session all")
                    return 1
                output_base = args.output
                if not output_base:
                    backup_stem = os.path.splitext(args.log)[0]
                    output_base = f"{backup_stem}_{selected.session_id}"
                try:
                    _process_one(
                        args,
                        output_override=output_base,
                        session_override=selected.session_id,
                    )
                except (OSError, RuntimeError, ValueError) as exc:
                    print(f"ERROR: {exc}")
                    return 1
                return 0
            return _export_rcz_backup(args, backup_sessions)
        elif args.session:
            print("ERROR: --session is only valid for a multi-session RCZ backup")
            return 1

    if args.log_type == "CAN" and not (args.dbc and os.path.isfile(args.dbc)):
        print(f"ERROR: DBC file {args.dbc} does not exist")
        return 1

    if args.log_type == "RCZ" and str(args.stint).lower() == "all":
        try:
            stints = _get_stints(args.log)
        except Exception as e:
            print(f"ERROR: Failed to read RCZ stints: {e}")
            return 1

        if len(stints) > 1:
            print(f"Auto-detected {len(stints)} stints in RCZ log: {stints}")
            base_output = args.output if args.output else args.log
            base_name, ext = os.path.splitext(base_output)
            for st in stints:
                st_out = f"{base_name}_stint{st}"
                print(f"\n=== Exporting Stint {st} -> {st_out} ===")
                _process_one(args, stint_override=str(st), output_override=st_out)
            print("Auto-stint split export complete.")
            return 0

    try:
        _process_one(args)
    except (OSError, RuntimeError, ValueError) as exc:
        print(f"ERROR: {exc}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
