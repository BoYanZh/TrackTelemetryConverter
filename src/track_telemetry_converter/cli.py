def parse_gear_ratio_thresholds(value):
    try:
        thresholds = tuple(float(part.strip()) for part in value.split(","))
    except ValueError as exc:
        raise argparse.ArgumentTypeError("gear ratio thresholds must be comma-separated numbers") from exc
    if len(thresholds) != 6 or any(a <= b for a, b in zip(thresholds, thresholds[1:], strict=False)):
        raise argparse.ArgumentTypeError(
            "gear ratio thresholds must contain six strictly descending values",
        )
    return thresholds


DESCRIPTION = """Generates MoTeC .ld files from external log files generated by: CAN bus dumps, CSV
 files, COBB Accessport CSV files, RaceChrono CSV files, TrackAddict CSV files,
 Tesla Track Mode CSV files, or Assetto Corsa ACTI .ld files"""

EPILOG = """The CAN bus log must be the same format as what is generated by 'candump' with the '-l'
option from the linux package can-utils. A MoTeC channel will be created for every signal in the
DBC file that has messages in the CAN log. The signal name and units will be directly copied from
the DBC file.

CSV files must have time as their first column. A MoTeC channel will be generated for all remaining
columns. All channels will not have any units assigned.

COBB Accessport CSV logs are simply generated by starting a logging session on the accessport. A
MoTeC channel will be created for every channel logged, the name and units will be directly copied
over.

RaceChrono CSV files are parsed looking for the 'Time (s)' header row and mapped to standard MoTeC
channel names and units automatically where applicable.

TrackAddict CSV files (RaceRender-Data format with '#' comment metadata) map GPS, speed,
acceleration, OBD channels, and the Lap column to standard MoTeC names and units; End/Split
points become GPS traps.

Tesla Track Mode CSV files (telemetry-v1-*.csv) rebuild the cumulative timeline across the
per-lap elapsed-time resets; Lap 0 becomes the Out Lap.

Assetto Corsa ACTI .ld files record simulator-frame coordinates (Car Coord X/Y)
instead of GPS. They require an explicit --track profile key (built-in profiles
cover Thunderhill West/East, Laguna Seca, Sonoma and Buttonwillow 1A CCW;
--anchor merges custom profiles) and a distinct --output, since the input
itself is already a .ld file (batch mode appends a _gps suffix instead).
--track thunderhill_auto picks the Thunderhill West/East bypass profile per
file from the Car Coord X minimum (above 435 m -> west, else east), so mixed
west+east directories convert in one batch run.
"""





