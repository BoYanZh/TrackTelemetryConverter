def process_one_file(args, stint_override=None, output_override=None, session_override=None):
    """Compatibility adapter for callers of the former CLI conversion helper."""
    request = ConversionRequest.from_namespace(args)
    options = request.options
    if stint_override is not None:
        options = replace(options, stint=str(stint_override))
    if output_override is not None:
        options = replace(options, output=output_override)
    if session_override is not None:
        options = replace(options, session=session_override)
    result = convert_request(replace(request, options=options))
    for message in result.messages:
        print(message)
    if result.status != "success":
        if result.status == "skipped":
            raise FileExistsError(result.error["message"] if result.error else "output already exists")
        raise ValueError(result.error["message"] if result.error else "conversion failed")
    return list(result.output_paths)


